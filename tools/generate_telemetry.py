def generate_telemetry(cfg: ScenarioConfig) -> Tuple[List[dict], Dict[str, float]]:
    """
    Run the full scenario and return the telemetry rows plus a diagnostics map.

    Rows are emitted in frame major order and, within a frame, in ascending
    device order, which makes the file directly reshapeable to a
    (frames, devices) tensor without a sort.
    """
    cfg.validate()

    mobility_rng = spawn_stream(cfg.seed, "mobility")
    shadow_rng = spawn_stream(cfg.seed, "shadowing")
    blockage_rng = spawn_stream(cfg.seed, "blockage")
    learning_rng = spawn_stream(cfg.seed, "learning-partition")
    loss_rng = spawn_stream(cfg.seed, "loss-observation")
    hardware_rng = spawn_stream(cfg.seed, "hardware")

    mobility = GaussMarkovMobility(cfg, mobility_rng)
    shadowing = ShadowingProcess(cfg, shadow_rng)
    blockage = SelfBlockageProcess(cfg, blockage_rng)
    profile = build_learning_profile(cfg, learning_rng)

    cpu_clock = hardware_rng.uniform(cfg.cpu_clock_hz_min, cfg.cpu_clock_hz_max, size=cfg.num_devices)
    compute_energy_per_step = cfg.dvfs_kappa * cfg.cpu_cycles_per_step * cpu_clock ** 2
    static_energy_per_frame = cfg.static_power_w * cfg.frame_duration_s
    tx_power_w = 10.0 ** ((cfg.tx_power_dbm - 30.0) / 10.0)
    radio_power_draw_w = tx_power_w / cfg.power_amplifier_efficiency

    noise_dbm = thermal_noise_power_dbm(
        cfg.bandwidth_hz, cfg.noise_density_dbm_per_hz, cfg.receiver_noise_figure_db
    )
    noise_mw = 10.0 ** (noise_dbm / 10.0)
    isolation_linear = 10.0 ** (-cfg.sidelobe_isolation_db / 10.0)
    payload_bits = float(cfg.model_parameters * cfg.quantization_bits)
    train_rng = spawn_stream(cfg.seed, "train-cycle")

    access_point = np.array(
        [cfg.access_point_xy_m[0], cfg.access_point_xy_m[1], cfg.access_point_height_m],
        dtype=float,
    )

    previous_position = mobility.position.copy()
    progress = np.zeros(cfg.num_devices, dtype=float)

    rows: List[dict] = []
    deadline_hits = 0
    blocked_frames = 0

    for step in range(cfg.num_frames):
        position_xy, speed = mobility.step()
        travelled = np.linalg.norm(position_xy - previous_position, axis=1)
        previous_position = position_xy.copy()

        position = np.column_stack(
            [position_xy, np.full(cfg.num_devices, cfg.device_height_m)]
        )
        distance = np.linalg.norm(position - access_point, axis=1)
        distance = np.maximum(distance, cfg.min_link_distance_m)

        fspl = free_space_path_loss_db(distance, cfg.carrier_hz, cfg.path_loss_exponent)
        absorption = molecular_absorption_db(distance, cfg.absorption_db_per_m)
        path_loss = fspl + absorption

        shadow_db = shadowing.step(travelled)
        blocked = blockage.step()
        blockage_loss = cfg.blockage_penalty_db * blocked.astype(float)

        rx_dbm = (
            cfg.tx_power_dbm
            + cfg.tx_array_gain_dbi
            + cfg.rx_array_gain_dbi
            - path_loss
            - shadow_db
            - blockage_loss
        )
        rx_mw = 10.0 ** (rx_dbm / 10.0)

        # Intra slice leakage from every other co scheduled beam.
        total_rx = float(np.sum(rx_mw))
        interference_mw = (total_rx - rx_mw) * isolation_linear

        sinr_linear = rx_mw / (noise_mw + interference_mw)
        sinr_db = 10.0 * np.log10(sinr_linear)

        capacity_bps = cfg.bandwidth_hz * np.log2(1.0 + sinr_linear)
        capacity_mbps = capacity_bps / 1.0e6
        latency_s = payload_bits / np.maximum(capacity_bps, 1.0)
        deadline_met = latency_s <= cfg.urllc_deadline_s

        progress = progress + deadline_met.astype(float)
        loss = local_training_loss(
            profile, progress, cfg.num_frames, loss_rng, cfg.loss_observation_noise
        )

        tx_occupancy_s = np.where(
            deadline_met, np.minimum(latency_s, cfg.frame_duration_s), 0.0
        )
        # Training cycle time on the measured device class, sampled from the
        # lognormal fitted to the Jetson rows. Reported on the slow timescale.
        train_cycle_ms = np.exp(
            cfg.train_cycle_log_mean
            + cfg.train_cycle_log_sigma * train_rng.standard_normal(cfg.num_devices)
        )
        # Compute energy from the device power envelope scaled by the duty
        # cycle of the training step within the frame.
        # Compute power follows the measured CPU load rather than the peak
        # envelope. The split between radio and compute energy is reported
        # separately because admission control can only ever reduce the
        # radio term, and on this device class the compute term dominates.
        cpu_load = np.clip(
            cfg.cpu_load_mean + cfg.cpu_load_sigma * train_rng.standard_normal(cfg.num_devices),
            0.0, 1.0,
        )
        compute_power_w = cfg.jetson_idle_w + (cfg.jetson_peak_w - cfg.jetson_idle_w) * cpu_load
        compute_energy = compute_power_w * cfg.frame_duration_s
        radio_energy = radio_power_draw_w * tx_occupancy_s

        energy = radio_energy + compute_energy + static_energy_per_frame

        deadline_hits += int(np.sum(deadline_met))
        blocked_frames += int(np.sum(blocked))

        for k in range(cfg.num_devices):
            rows.append(
                {
                    "TimeStep": step,
                    "TimeSeconds": step * cfg.frame_duration_s,
                    "DeviceID": f"D{k:02d}",
                    "PosX_m": position[k, 0],
                    "PosY_m": position[k, 1],
                    "PosZ_m": position[k, 2],
                    "Distance_m": distance[k],
                    "Speed_mps": speed[k],
                    "PathLoss_dB": path_loss[k],
                    "AbsorptionLoss_dB": absorption[k],
                    "Shadowing_dB": shadow_db[k],
                    "BlockageFlag": int(blocked[k]),
                    "RxPower_dBm": rx_dbm[k],
                    "SINR_dB": sinr_db[k],
                    "LinkCapacity_Mbps": capacity_mbps[k],
                    "UplinkLatency_ms": latency_s[k] * 1.0e3,
                    "DeadlineMet": int(deadline_met[k]),
                    "LocalTrainingLoss": loss[k],
                    "Energy_Joule": energy[k],
                    "TrainCycle_ms": train_cycle_ms[k],
                    "RadioEnergy_Joule": radio_energy[k],
                    "ComputeEnergy_Joule": compute_energy[k],
                }
            )

    total = cfg.num_frames * cfg.num_devices
    diagnostics = {
        "derived_dwell_frames": cfg.blocker_width_m / cfg.blocker_speed_mps / cfg.frame_duration_s,
        "absorption_db_per_m": cfg.absorption_db_per_m,
        "noise_power_dbm": noise_dbm,
        "deadline_success_rate": deadline_hits / total,
        "empirical_blockage_rate": blocked_frames / total,
        "requested_blockage_rate": cfg.blockage_probability,
        "payload_bits": payload_bits,
        "rows": float(total),
    }
    return rows, diagnostics


