def free_space_path_loss_db(distance_m: np.ndarray, carrier_hz: float, exponent: float = 2.0) -> np.ndarray:
    """
    Friis free space path loss in dB for the given separation and carrier.

    The expression is the explicit 20*log10(4*pi*d*f/c) form rather than a
    fitted constant plus a slope, so the model stays exact when the carrier is
    retuned anywhere across the 100 to 300 GHz range.
    """
    # Close in model with a 1 m free space reference. exponent = 2 is Friis.
    return (20.0 * np.log10(4.0 * math.pi * carrier_hz / SPEED_OF_LIGHT)
            + 10.0 * exponent * np.log10(distance_m))


def molecular_absorption_db(distance_m: np.ndarray, coefficient_db_per_m: float) -> np.ndarray:
    """
    Molecular absorption loss in dB under the Beer Lambert law.

    A coefficient expressed in dB/m is already the logarithmic form of the
    transmittance exp(-kappa_abs_linear * d), so the loss is strictly linear in
    distance. At 0.3 THz in standard humid air this term is what makes the link
    budget distance limited in a way that mmWave links are not.
    """
    return coefficient_db_per_m * distance_m


def thermal_noise_power_dbm(bandwidth_hz: float, density_dbm_per_hz: float, noise_figure_db: float) -> float:
    """Integrate the noise density over the slice and add the receiver figure."""
    return density_dbm_per_hz + 10.0 * math.log10(bandwidth_hz) + noise_figure_db


class ShadowingProcess:
    """
    Spatially correlated log normal shadowing.

    The correlation coefficient of the first order autoregressive update is
    rho = exp(-delta_d / d_corr) after Gudmundson, where delta_d is the distance
    actually travelled during the frame. The innovation variance is scaled by
    (1 - rho^2) so that the marginal standard deviation stays pinned at the
    configured value no matter how fast the device moves.
    """

    def __init__(self, cfg: ScenarioConfig, rng: np.random.Generator) -> None:
        self.cfg = cfg
        self.rng = rng
        self.state = cfg.shadowing_sigma_db * rng.standard_normal(cfg.num_devices)

    def step(self, travelled_m: np.ndarray) -> np.ndarray:
        sigma = self.cfg.shadowing_sigma_db
        if sigma == 0.0:
            return np.zeros_like(self.state)
        rho = np.exp(-np.abs(travelled_m) / self.cfg.shadowing_decorrelation_m)
        innovation = self.rng.standard_normal(self.cfg.num_devices)
        self.state = rho * self.state + np.sqrt(np.maximum(1.0 - rho ** 2, 0.0)) * sigma * innovation
        return self.state.copy()


class SelfBlockageProcess:
    """
    Two state Markov self blockage model for the line of sight beam.

    The transition probabilities are solved from the requested stationary
    blockage probability p_b and the requested mean blockage dwell time L, which
    gives p_recover = 1/L and p_block = p_b / (L * (1 - p_b)). Modelling dwell
    time explicitly matters because a temporally clustered outage stalls a
    federated round in a way that an independent per frame coin flip never
    reproduces.
    """

    def __init__(self, cfg: ScenarioConfig, rng: np.random.Generator) -> None:
        self.rng = rng
        p_b = cfg.blockage_probability
        dwell = cfg.blockage_mean_duration_frames
        self.p_recover = 1.0 / dwell
        self.p_block = float(np.clip(p_b / (dwell * (1.0 - p_b)), 0.0, 1.0)) if p_b > 0.0 else 0.0
        self.blocked = rng.random(cfg.num_devices) < p_b

    def step(self) -> np.ndarray:
        draw = self.rng.random(self.blocked.shape[0])
        recover = self.blocked & (draw < self.p_recover)
        newly = (~self.blocked) & (draw < self.p_block)
        self.blocked = (self.blocked & ~recover) | newly
        return self.blocked.copy()


# --------------------------------------------------------------------------
# Non-IID federated learning workload
# --------------------------------------------------------------------------

@dataclass
class LearningProfile:
    """Per device learning heterogeneity derived from the local label skew."""

    decay_multiplier: np.ndarray = field(default_factory=lambda: np.empty(0))
    loss_start: np.ndarray = field(default_factory=lambda: np.empty(0))
    loss_floor: np.ndarray = field(default_factory=lambda: np.empty(0))
    label_histogram: np.ndarray = field(default_factory=lambda: np.empty(0))
    skew_index: np.ndarray = field(default_factory=lambda: np.empty(0))


def build_learning_profile(cfg: ScenarioConfig, rng: np.random.Generator, num_classes: int = 10) -> LearningProfile:
    """
    Draw the non-IID partition and turn it into loss trajectory parameters.

    A Dirichlet draw with concentration alpha gives each device a distinct label
    histogram. Its Kullback Leibler divergence from the uniform reference is a
    scalar skew index in the natural range [0, log(num_classes)]. A strongly
    skewed client learns its own biased objective faster locally yet settles on a
    higher loss against the global objective, which is exactly the tension that
    the unique exponential multipliers below encode.
    """
    histogram = rng.dirichlet(np.full(num_classes, cfg.dirichlet_alpha), size=cfg.num_devices)
    uniform = 1.0 / num_classes
    safe = np.clip(histogram, 1e-12, None)
    kl = np.sum(safe * np.log(safe / uniform), axis=1)
    skew = kl / math.log(num_classes)

    # Unique exponential multiplier per device. The skew term guarantees that no
    # two clients share a decay rate even before the jitter is applied.
    jitter = rng.uniform(0.88, 1.12, size=cfg.num_devices)
    decay = cfg.loss_decay_base * (1.0 + cfg.loss_decay_spread * skew) * jitter

    start = cfg.loss_initial * rng.uniform(0.96, 1.05, size=cfg.num_devices)
    floor = cfg.loss_floor_ideal * (1.0 + 2.4 * skew)

    return LearningProfile(
        decay_multiplier=decay,
        loss_start=start,
        loss_floor=floor,
        label_histogram=histogram,
        skew_index=skew,
    )


def local_training_loss(
    profile: LearningProfile,
    progress: np.ndarray,
    total_frames: int,
    rng: np.random.Generator,
    noise_scale: float,
) -> np.ndarray:
    """
    Evaluate the skewed exponential loss trajectory for the current frame.

    The curve is L_floor + (L_start - L_floor) * exp(-lambda_k * p_k), where p_k
    is the normalised effective progress of client k. Progress advances only on
    frames whose link met the URLLC deadline, so a client sitting in a blockage
    plateau on its previous loss value instead of improving.
    """
    normalised = progress / max(total_frames, 1)
    decayed = np.exp(-profile.decay_multiplier * normalised)
    clean = profile.loss_floor + (profile.loss_start - profile.loss_floor) * decayed
    observed = clean + noise_scale * clean * rng.standard_normal(clean.shape[0])
    return np.maximum(observed, 1e-4)


