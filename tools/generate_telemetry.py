def write_csv(rows: Sequence[dict], path: str, decimals: int) -> str:
    """Write the telemetry to a structured CSV file and return the path."""
    directory = os.path.dirname(os.path.abspath(path))
    if directory and not os.path.isdir(directory):
        os.makedirs(directory, exist_ok=True)

    integer_fields = {"TimeStep", "BlockageFlag", "DeadlineMet"}
    with open(path, "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(CSV_FIELDS))
        writer.writeheader()
        for row in rows:
            encoded = {}
            for key in CSV_FIELDS:
                value = row[key]
                if key in integer_fields:
                    encoded[key] = int(value)
                elif isinstance(value, (int, float, np.floating, np.integer)):
                    encoded[key] = f"{float(value):.{decimals}f}"
                else:
                    encoded[key] = value
            writer.writerow(encoded)
    return path


def verify_dataset(rows: Sequence[dict], cfg: ScenarioConfig) -> None:
    """
    Post generation self test.

    Checks row count, finiteness and the sign of the physical columns.
    """
    expected = cfg.num_frames * cfg.num_devices
    if len(rows) != expected:
        raise AssertionError(f"Expected {expected} rows but produced {len(rows)}")

    numeric = [f for f in CSV_FIELDS if f != "DeviceID"]
    matrix = np.array([[float(row[f]) for f in numeric] for row in rows])
    if not np.all(np.isfinite(matrix)):
        raise AssertionError("Non finite values detected in the telemetry matrix")

    index = {name: i for i, name in enumerate(numeric)}
    if np.any(matrix[:, index["LinkCapacity_Mbps"]] <= 0.0):
        raise AssertionError("Shannon capacity must be strictly positive")
    if np.any(matrix[:, index["Energy_Joule"]] <= 0.0):
        raise AssertionError("Per frame energy must be strictly positive")
    if np.any(matrix[:, index["LocalTrainingLoss"]] <= 0.0):
        raise AssertionError("Training loss must be strictly positive")
    if np.any(matrix[:, index["Distance_m"]] < cfg.min_link_distance_m - 1e-9):
        raise AssertionError("Link distance fell below the configured guard")

    identifiers = sorted({row["DeviceID"] for row in rows})
    if len(identifiers) != cfg.num_devices:
        raise AssertionError("Unexpected number of distinct device identifiers")


def print_summary(rows: Sequence[dict], cfg: ScenarioConfig, diagnostics: Dict[str, float], path: str) -> None:
    """Print a compact console report of the generated run."""
    print("")
    print("Urban 6G sub-THz FRL telemetry generation complete")
    print("-" * 62)
    print(f"  Output file            {path}")
    print(f"  Rows written           {len(rows)}")
    print(f"  Devices                {cfg.num_devices}")
    print(f"  Frames                 {cfg.num_frames} "
          f"({cfg.num_frames * cfg.frame_duration_s:.2f} s of wall clock)")
    print(f"  Carrier                {cfg.carrier_hz / 1e12:.3f} THz")
    print(f"  Slice bandwidth        {cfg.bandwidth_hz / 1e9:.2f} GHz")
    print(f"  Absorption coefficient {cfg.absorption_db_per_m:.6f} dB/m "
          f"(ITU-R P.676, standard atmosphere)")
    print(f"  Blockage dwell         {cfg.blockage_mean_duration_frames:.0f} frames "
          f"(derived {diagnostics['derived_dwell_frames']:.0f} from transit geometry)")
    print(f"  Thermal noise power    {diagnostics['noise_power_dbm']:.2f} dBm")
    print(f"  Blockage rate          {diagnostics['empirical_blockage_rate']:.3f} "
          f"(target {diagnostics['requested_blockage_rate']:.3f})")
    print(f"  Deadline success rate  {diagnostics['deadline_success_rate']:.3f}")
    print(f"  Master seed            {cfg.seed}")
    print("-" * 62)

    numeric_columns = ["SINR_dB", "LinkCapacity_Mbps", "LocalTrainingLoss",
                       "Energy_Joule", "RadioEnergy_Joule",
                       "ComputeEnergy_Joule", "TrainCycle_ms"]
    print("  Column statistics")
    print(f"    {'column':<22}{'mean':>12}{'std':>12}{'min':>12}{'max':>12}")
    for name in numeric_columns:
        values = np.array([float(row[name]) for row in rows])
        print(f"    {name:<22}{values.mean():>12.4f}{values.std():>12.4f}"
              f"{values.min():>12.4f}{values.max():>12.4f}")

    print("")
    print("  Per device non-IID signature, final loss and mean capacity")
    print(f"    {'device':<10}{'final loss':>14}{'mean Mbps':>14}{'blockage':>12}")
    for identifier in sorted({row["DeviceID"] for row in rows}):
        subset = [row for row in rows if row["DeviceID"] == identifier]
        final_loss = float(subset[-1]["LocalTrainingLoss"])
        mean_capacity = float(np.mean([row["LinkCapacity_Mbps"] for row in subset]))
        blockage_rate = float(np.mean([row["BlockageFlag"] for row in subset]))
        print(f"    {identifier:<10}{final_loss:>14.4f}{mean_capacity:>14.2f}{blockage_rate:>12.3f}")
    print("")


