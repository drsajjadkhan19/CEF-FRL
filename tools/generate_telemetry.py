def parse_arguments(argv: Sequence[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate a reproducible urban 6G sub-THz FRL telemetry dataset."
    )
    parser.add_argument("--seed", type=int, default=ScenarioConfig.seed,
                        help="Master seed controlling every derived stream.")
    parser.add_argument("--devices", type=int, default=ScenarioConfig.num_devices,
                        help="Number of moving embodied IoT clients.")
    parser.add_argument("--frames", type=int, default=ScenarioConfig.num_frames,
                        help="Number of discrete communication frames.")
    parser.add_argument("--output", type=str, default=ScenarioConfig.output_path,
                        help="Destination CSV path.")
    parser.add_argument("--quiet", action="store_true",
                        help="Suppress the console summary report.")
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_arguments(sys.argv[1:] if argv is None else argv)
    cfg = ScenarioConfig(
        seed=args.seed,
        num_devices=args.devices,
        num_frames=args.frames,
        output_path=args.output,
    )

    rows, diagnostics = generate_telemetry(cfg)
    verify_dataset(rows, cfg)
    path = write_csv(rows, cfg.output_path, cfg.float_decimals)

    if not args.quiet:
        print_summary(rows, cfg, diagnostics, path)
        try:
            import pandas as pd

            frame = pd.read_csv(path)
            print("  Head of the written file")
            print(frame.head(6).to_string(index=False))
            print("")
        except ImportError:
            print("  Pandas is unavailable, skipping the file preview.")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
