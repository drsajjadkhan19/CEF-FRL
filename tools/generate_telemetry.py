#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Channel trace generator for the CEF-FRL experiments.

Produces a reproducible frame-level telemetry stream for moving embodied IoT
clients served by one sub-THz access point in an urban micro-cell. Every
physical-layer quantity follows a closed-form model, so the file is
regenerated exactly from the seed.

Physical layer chain (per client k, per frame t)

    d_k(t)      Euclidean three dimensional separation from client to the
                access point, driven by a Gauss Markov correlated mobility
                process with reflecting cell boundaries.

    PL_CI       20*log10(4*pi*f/c) + 10*n*log10(d), the close-in path loss
                with a 1 m reference and exponent n = 2.1, at 0.3 THz.

    A_abs       kappa_abs * d, molecular absorption with
                kappa_abs = 0.005203 dB/m (ITU-R P.676).

    PL_k(t)     PL_CI + A_abs, in dB.

    chi_k(t)    Spatially correlated log normal shadowing with a standard
                deviation of 2.8 dB, generated by a first order
                autoregressive process whose correlation coefficient follows
                the exponential Gudmundson model with a decorrelation
                distance of 10 m.

    B_k(t)      Self blockage indicator from a two state Markov chain whose
                stationary blockage probability and mean blockage dwell time
                are both configurable. An active blockage subtracts a further
                30.0 dB of channel gain.

    P_rx        P_tx + G_tx + G_rx - PL - chi - 30*B, in dBm.

    N_0         Thermal noise power from a density of -174 dBm/Hz integrated
                over the 2 GHz slice bandwidth, plus a receiver noise figure.

    I_k(t)      Co scheduled intra cell leakage from the other clients sharing
                the slice, attenuated by the beam sidelobe isolation.

    SINR        P_rx / (N_0 + I_k), reported in dB.

    C_k(t)      W * log2(1 + SINR_linear), the continuous Shannon capacity of
                the slice, reported in Mbps.

Learning layer

    Each client owns a Dirichlet sampled label histogram, so the local data
    distributions are non identically distributed by construction. The
    divergence of that histogram from the uniform reference sets both the
    attainable loss floor and a unique exponential decay multiplier
    lambda_k, which is what skews the local loss trajectories across the
    fleet. Progress accumulates only on frames where the link can deliver the
    gradient payload inside the URLLC deadline, so the loss column is
    physically coupled to the channel columns rather than being an independent
    synthetic curve.

Energy layer

    Per frame energy sums the radio front end term P_tx/eta_pa over the actual
    transmission occupancy, the dynamic voltage frequency scaling compute term
    kappa_c * omega * f_clock^2 for a local gradient step, and a static
    sensing and idle term.

Usage

    python3 generate_telemetry.py --output ../data/telemetry_v3.csv
    python3 generate_telemetry.py --seed 2026 --frames 1000 --devices 5
    python3 generate_telemetry.py --output my_run.csv --quiet

The script depends only on NumPy and the Python standard library. Pandas is
used opportunistically for the console summary when it is importable, and the
script is fully functional without it.
"""

