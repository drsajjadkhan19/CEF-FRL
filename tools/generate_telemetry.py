# --------------------------------------------------------------------------
# Deterministic sub stream helper
# --------------------------------------------------------------------------

def spawn_stream(master_seed: int, label: str) -> np.random.Generator:
    """
    Build an independent PRNG stream whose seed is a stable hash of a label.

    Deriving one generator per physical process keeps the streams decoupled, so
    changing the number of frames does not perturb, for instance, the Dirichlet
    label histograms. That property is what makes an ablation over a single
    parameter comparable against the baseline run.
    """
    digest = hashlib.sha256(f"{master_seed}::{label}".encode("utf-8")).digest()
    derived = int.from_bytes(digest[:8], byteorder="big", signed=False)
    return np.random.default_rng(np.random.SeedSequence([master_seed, derived % (2 ** 32)]))


# --------------------------------------------------------------------------
# Mobility
# --------------------------------------------------------------------------

class GaussMarkovMobility:
    """
    Gauss Markov correlated mobility inside a square cell.

    Speed and heading are first order autoregressive processes, which yields
    smooth physically plausible tracks rather than the discontinuous jumps of an
    independent random walk. Boundaries reflect, so the fleet stays inside the
    service area for the whole run and the distance statistics remain stationary.
    """

    def __init__(self, cfg: ScenarioConfig, rng: np.random.Generator) -> None:
        self.cfg = cfg
        self.rng = rng
        k = cfg.num_devices

        margin = 0.12 * cfg.area_size_m
        self.position = rng.uniform(margin, cfg.area_size_m - margin, size=(k, 2))
        self.mean_speed = rng.uniform(cfg.speed_min_mps, cfg.speed_max_mps, size=k)
        self.speed = self.mean_speed.copy()
        self.mean_heading = rng.uniform(-math.pi, math.pi, size=k)
        self.heading = self.mean_heading.copy()

    def step(self) -> Tuple[np.ndarray, np.ndarray]:
        """Advance one frame and return the updated positions and speeds."""
        cfg = self.cfg
        alpha = cfg.mobility_memory
        root = math.sqrt(1.0 - alpha ** 2)
        k = cfg.num_devices

        self.speed = (
            alpha * self.speed
            + (1.0 - alpha) * self.mean_speed
            + root * cfg.speed_jitter_mps * self.rng.standard_normal(k)
        )
        self.speed = np.clip(self.speed, cfg.speed_min_mps, cfg.speed_max_mps)

        self.heading = (
            alpha * self.heading
            + (1.0 - alpha) * self.mean_heading
            + root * cfg.heading_jitter_rad * self.rng.standard_normal(k)
        )

        displacement = self.speed * cfg.frame_duration_s
        self.position[:, 0] += displacement * np.cos(self.heading)
        self.position[:, 1] += displacement * np.sin(self.heading)
        self._reflect()
        return self.position.copy(), self.speed.copy()

    def _reflect(self) -> None:
        """Mirror any excursion back into the cell and flip the heading."""
        upper = self.cfg.area_size_m
        for axis in (0, 1):
            column = self.position[:, axis]
            below = column < 0.0
            above = column > upper
            column[below] = -column[below]
            column[above] = 2.0 * upper - column[above]
            np.clip(column, 0.0, upper, out=column)
            if np.any(below | above):
                flipped = below | above
                if axis == 0:
                    self.heading[flipped] = math.pi - self.heading[flipped]
                else:
                    self.heading[flipped] = -self.heading[flipped]


